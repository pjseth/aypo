"""Bake ANTHROPIC_API_KEY from the environment into app/js/env.js.

The app is a static page with no server, so there is no runtime environment to read. The
build is where the environment exists, which is what this is for:

    ANTHROPIC_API_KEY=sk-ant-... py -3.11 tools/make_env.py
    py -3.11 tools/make_env.py --clear

`app/js/env.js` is in .gitignore (the stub was committed with `git add -f`), so a key written
here cannot be committed by accident.

Without a key every feature still works: the negotiation brief and the market bulletin are
written by the app from the figures on screen, and that deterministic path is the one the demo
runs on. A key only changes who writes the prose - never where the numbers come from.

Calling the API straight from a page means the key reaches the browser. That is a demo
affordance, not a design: a real deployment puts the call behind the customer's own server,
and the app says so on screen.
"""

import argparse
import json
import os
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "js" / "env.js"

HEADER = """/* Generated by tools/make_env.py - do not edit, and do not commit with a key in it.
   This file is in .gitignore for exactly that reason. See tools/make_env.py. */
"""

STUB = '''/* Build-time environment, for the one thing the app cannot read at runtime: an API key.

   This file is a stub and it is listed in .gitignore, so whatever `tools/make_env.py` writes
   over it locally can never be committed. Run

       ANTHROPIC_API_KEY=sk-ant-... py -3.11 tools/make_env.py

   to bake the key in, or paste one into the app and it is kept in this browser's
   localStorage instead. Either way the desk works without one: every generated document has
   a deterministic template behind it, and that template is what the demo runs on. */
window.GD_ENV = { ANTHROPIC_API_KEY: "" };
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--clear", action="store_true", help="write the empty stub back")
    args = ap.parse_args()

    if args.clear:
        OUT.write_text(STUB, encoding="utf-8")
        print("cleared %s" % OUT)
        return 0

    key = os.environ.get("ANTHROPIC_API_KEY", "").strip()
    if not key:
        print("ANTHROPIC_API_KEY is not set in the environment.")
        print("Nothing written. The app runs on its template path, which is the default.")
        return 1

    OUT.write_text(HEADER + "window.GD_ENV = " +
                   json.dumps({"ANTHROPIC_API_KEY": key}, separators=(",", ":")) + ";\n",
                   encoding="utf-8")
    print("wrote %s with a key ending %s" % (OUT, key[-6:]))
    print("app/js/env.js is gitignored. Run --clear before sharing the tree.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
